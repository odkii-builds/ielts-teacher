'use strict';
// Ник Telegram для листа ожидания: «@ник», без пробелов. Ник в Telegram: 5–32 символа, латиница, цифры, «_», первая — буква.
// Если «@» забыли, добавляем сами. Возвращает нормализованный «@ник» или '' (не подходит).
// То же правило продублировано в app/js/extras.js (клиент не может подключить этот модуль).
const RE = /^@[A-Za-z][A-Za-z0-9_]{4,31}$/;
function normTg(s) {
  let t = String(s == null ? '' : s).trim();
  if (!t) return '';
  if (t[0] !== '@') t = '@' + t;
  return RE.test(t) ? t : '';
}
module.exports = { normTg };
